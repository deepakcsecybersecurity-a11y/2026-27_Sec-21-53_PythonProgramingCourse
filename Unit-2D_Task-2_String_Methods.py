str1 = "  Hello Python World  "

print("Upper:", str1.upper())
print("Lower:", str1.lower())
print("Strip:", str1.strip())

str2 = "Hello Python World"
print("Split:", str2.split())

words = ["Hello", "Python", "World"]
print("Join:", " ".join(words))

print("Replace:", str2.replace("Python", "Java"))

print("Find:", str2.find("Python"))