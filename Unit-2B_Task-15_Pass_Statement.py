#For loop:
N = int(input("Enter the value of n: "))
for i in range(1, N + 1):
    if i == 5:
        pass #the code passes/ skips the number 5
    print(i)

#while loop
N = int(input("Enter the value on N: "))
i = 1

while i <= N:
    if i == 5:
        pass
    print(i)
    i = i + 1